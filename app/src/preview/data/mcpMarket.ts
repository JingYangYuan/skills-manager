const remote = (
  id: string,
  label: string,
  url: string,
  inputs: McpInstallInput[] = [],
): McpInstallOption => ({
  id,
  kind: 'remote',
  label,
  transport: 'http',
  url,
  headers: {},
  command: null,
  args: [],
  env: {},
  inputs,
  supported: true,
  unsupportedReason: null,
  packageType: null,
  warnings: [],
});

const pkg = (
  id: string,
  label: string,
  packageType: string,
  command: string,
  args: string[],
  inputs: McpInstallInput[] = [],
): McpInstallOption => ({
  id,
  kind: 'package',
  label,
  transport: 'stdio',
  url: null,
  headers: {},
  command,
  args,
  env: {},
  inputs,
  supported: true,
  unsupportedReason: null,
  packageType,
  warnings: [],
});

const secretInput = (
  key: string,
  label: string,
  description: string,
): McpInstallInput => ({
  key,
  label,
  description,
  required: true,
  secret: true,
  defaultValue: null,
  placeholder: null,
  choices: [],
  kind: 'env',
});

